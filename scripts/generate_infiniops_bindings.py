"""Generate typed bindings from the installed InfiniOps public SDK.

The installed factory declarations are generated by InfiniOps itself. We read
only their signatures; generated consumers call the public operator classes,
never generated_dispatch or backend implementation symbols.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re


def split_parameters(text):
    parts, begin, depth = [], 0, 0
    for i, char in enumerate(text):
        if char in "<([":
            depth += 1
        elif char in ">)]":
            depth -= 1
        elif char == "," and depth == 0:
            parts.append(text[begin:i].strip())
            begin = i + 1
    parts.append(text[begin:].strip())
    return parts


def normalize_type(text):
    text = re.sub(r"\bconst\b", "", text).replace("&", "").strip()
    return re.sub(r"\s+", "", text).replace("::infini::ops::", "")


def supported_type(name):
    if name.startswith("std::optional<") and name.endswith(">"):
        return supported_type(name[14:-1])
    return name in {
        "Tensor", "std::vector<Tensor>", "int", "int32_t", "int64_t",
        "size_t", "std::size_t", "float", "double", "bool", "std::string",
        "std::vector<int64_t>", "DataType", "Tensor::Size",
    }


def discover(header):
    blocks = re.findall(
        r"struct\s+detail::OperatorFactory<(?:\:\:infini::ops::)?(\w+)>\s*\{(.*?)\};",
        header, re.S,
    )
    if not blocks:
        raise ValueError("No public InfiniOps factory declarations found; incompatible SDK")
    operations, unsupported = [], []
    for operation, body in blocks:
        constructors = []
        for params in re.findall(r"\bMake\((.*?)\);", body, re.S):
            constructors.append(tuple(normalize_type(re.match(r"(.+?)\s+(\w+)$", p).group(1))
                                      for p in split_parameters(params)[1:]))
        seen = set()
        for params in re.findall(r"static\s+void\s+Call\((.*?)\);", body, re.S):
            fields = []
            for field in split_parameters(params)[2:]:
                match = re.fullmatch(r"(.+?)\s+(\w+)", field, re.S)
                if not match:
                    raise ValueError(f"Unrecognized public parameter: {field}")
                fields.append({"name": match[2], "type": normalize_type(match[1])})
            types = tuple(f["type"] for f in fields)
            if types not in constructors or (operation, types) in seen:
                continue
            seen.add((operation, types))
            if not all(supported_type(t) for t in types):
                unsupported.append({"name": operation, "parameters": fields})
                continue
            operations.append({"name": operation, "parameters": fields})
    return operations, unsupported


def generate(header, output, manifest):
    content = Path(header).read_text(encoding="utf-8")
    operations, unsupported = discover(content)
    lines = ['// Generated from the installed InfiniOps SDK. Do not edit.',
             '#include "execution.h"', '#include <infini/ops.h>',
             'namespace infini::infiniops {', 'void registerGeneratedBindings(Registry &registry) {']
    for operation in operations:
        fields = operation["parameters"]
        params = ", ".join('{"' + f["name"] + '", "' + f["type"] + '"}' for f in fields)
        values = ", ".join(f'getArgument<{f["type"].replace("Tensor", "TensorView")}>(values.at({i}))' for i, f in enumerate(fields))
        lines += [f'  registry.add("{operation["name"]}", {{{params}}},',
                  '    [](const Values &values, const WorkspaceAllocator &allocate) {',
                  f'      return prepareTyped<::infini::ops::{operation["name"]}>(allocate, {values});',
                  '    });']
    lines += ['}', '} // namespace infini::infiniops', '']
    Path(output).parent.mkdir(parents=True, exist_ok=True)
    Path(output).write_text("\n".join(lines), encoding="utf-8")
    Path(manifest).write_text(json.dumps({"sdk_sha256": hashlib.sha256(content.encode()).hexdigest(),
                                        "operations": operations, "unsupported_signatures": unsupported},
                                       indent=2) + "\n", encoding="utf-8")
    print(f"Generated {len(operations)} public signatures; {len(unsupported)} unsupported signatures recorded")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--header", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--manifest", required=True)
    args = parser.parse_args()
    generate(args.header, args.output, args.manifest)
